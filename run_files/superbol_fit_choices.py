# Optional recorded plans for SuperBol runs using Gopreaux photometry.
# Entries have the same shape as SUPERBOL_FIT_CHOICES and are kept separate
# because the source photometry has different bands and epoch coverage.
GOPREAUX_FIT_CHOICES = {}


def gopreaux_fit_choice(band_epochs, reference_filter):
    """Build a conservative plan from Gopreaux's available bands and epochs."""
    reference_epochs = band_epochs[reference_filter]
    first_ref, last_ref = min(reference_epochs), max(reference_epochs)
    return {
        "reference_filter": reference_filter,
        "bands": {
            band: (min(2, len(epochs) - 1),
                   "c" if min(epochs) > first_ref else None,
                   "c" if max(epochs) < last_ref else None)
            for band, epochs in band_epochs.items() if band != reference_filter
        },
    }
